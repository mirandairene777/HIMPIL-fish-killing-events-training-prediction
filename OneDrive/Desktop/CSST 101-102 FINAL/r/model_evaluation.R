# HIMPIL Phase 7c - model-evaluation figures in R
#
# The current project has no trained model and no predictions. This script
# therefore writes an explicit not-available status and does not fabricate a
# confusion matrix, ROC curve or precision-recall curve.
#
# If a later, approved model writes data/outputs/test_predictions.csv with
# columns y_true and y_score, this script will evaluate that file.
#
# Run from anywhere:
#   "C:\Program Files\R\R-4.6.1\bin\Rscript.exe" r/model_evaluation.R

suppressPackageStartupMessages({
  library(readr)
  library(dplyr)
  library(ggplot2)
})

script_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
script_dir <- if (length(script_arg)) {
  dirname(normalizePath(sub("^--file=", "", script_arg[[1]])))
} else {
  getwd()
}
root <- normalizePath(file.path(script_dir, ".."))
processed <- file.path(root, "data", "processed")
outputs <- file.path(root, "data", "outputs")
tables <- file.path(root, "reports", "tables")
figures <- file.path(root, "reports", "figures")
dir.create(outputs, recursive = TRUE, showWarnings = FALSE)
dir.create(tables, recursive = TRUE, showWarnings = FALSE)
dir.create(figures, recursive = TRUE, showWarnings = FALSE)

model_path <- file.path(processed, "modeling_dataset.csv")
predictions_path <- file.path(outputs, "test_predictions.csv")

model_data <- if (file.exists(model_path)) {
  read_csv(model_path, show_col_types = FALSE)
} else {
  tibble()
}

n_rows <- nrow(model_data)
has_label <- "fish_kill_within_24h" %in% names(model_data)
n_labelled <- if (has_label) sum(!is.na(model_data$fish_kill_within_24h)) else 0
positive <- if (has_label) sum(model_data$fish_kill_within_24h == 1, na.rm = TRUE) else 0
negative <- if (has_label) sum(model_data$fish_kill_within_24h == 0, na.rm = TRUE) else 0

status <- tibble(
  check = c(
    "modelling_dataset_exists",
    "modelling_dataset_rows",
    "label_column_present",
    "labelled_rows",
    "positive_labels",
    "negative_labels",
    "test_predictions_file",
    "model_evaluation_status"
  ),
  value = c(
    file.exists(model_path),
    n_rows,
    has_label,
    n_labelled,
    positive,
    negative,
    file.exists(predictions_path),
    if (file.exists(predictions_path) && positive > 0 && negative > 0) {
      "available"
    } else {
      "not_available"
    }
  ),
  note = c(
    "Header-only template is expected at this stage",
    "No invented observations",
    "Target is blocked by prepare_labels.py",
    "No 24-hour labels were generated",
    "No documented positive windows",
    "No credible negative windows",
    "No model has been trained",
    "No metric is reported without real predictions"
  )
)

write_csv(status, file.path(tables, "r_model_evaluation_status.csv"))

if (!file.exists(predictions_path) || positive == 0 || negative == 0) {
  notes <- c(
    "# R model-evaluation status",
    "",
    "**Status: not available.**",
    "",
    "No model was trained and no prediction file exists. The Python feasibility",
    "assessment found one event period, no pre-event dated observation, no credible",
    "negative windows and no daily water-quality series. A confusion matrix, ROC",
    "curve or precision-recall curve would therefore be fabricated, so none is",
    "produced.",
    "",
    "## Requirements before this script can report metrics",
    "",
    "1. `data/processed/modeling_dataset.csv` contains real labelled rows.",
    "2. Both classes are present in the held-out test period.",
    "3. `data/outputs/test_predictions.csv` contains `y_true` and `y_score` for the",
    "   untouched test period, generated by an approved chronological evaluation.",
    "",
    "The script will then report the 0.5-threshold confusion matrix, precision,",
    "recall, F1, and a precision-recall curve.",
    "",
    "## Files",
    "",
    "- `reports/tables/r_model_evaluation_status.csv`",
    "- No evaluation figure was produced."
  )
  writeLines(notes, file.path(tables, "r_model_evaluation_notes.md"), useBytes = TRUE)
  message("Model evaluation: not available (no real predictions)")
  quit(save = "no", status = 0)
}

# ---------------------------------------------------------------------------
# Optional evaluation path, used only after a real approved model exists
# ---------------------------------------------------------------------------

predictions <- read_csv(predictions_path, show_col_types = FALSE)
required <- c("y_true", "y_score")
if (!all(required %in% names(predictions))) {
  stop("test_predictions.csv must contain y_true and y_score")
}

predictions <- predictions |>
  filter(!is.na(y_true), !is.na(y_score)) |>
  mutate(y_true = as.integer(y_true), y_score = as.numeric(y_score))

if (length(unique(predictions$y_true)) < 2) {
  stop("The held-out predictions contain only one class; metrics are undefined")
}

threshold <- 0.5
predicted <- as.integer(predictions$y_score >= threshold)
truth <- predictions$y_true

tp <- sum(predicted == 1 & truth == 1)
fp <- sum(predicted == 1 & truth == 0)
tn <- sum(predicted == 0 & truth == 0)
fn <- sum(predicted == 0 & truth == 1)

safe_divide <- function(numerator, denominator) {
  if (denominator == 0) NA_real_ else numerator / denominator
}

precision <- safe_divide(tp, tp + fp)
recall <- safe_divide(tp, tp + fn)
f1 <- if (is.na(precision) || is.na(recall) || (precision + recall) == 0) {
  NA_real_
} else {
  2 * precision * recall / (precision + recall)
}

confusion <- tibble(
  actual = c("event", "event", "no_event", "no_event"),
  predicted = c("event", "no_event", "event", "no_event"),
  cell = c("TP", "FN", "FP", "TN"),
  count = c(tp, fn, fp, tn)
)
write_csv(confusion, file.path(tables, "r_confusion_matrix.csv"))

metrics <- tibble(
  threshold = threshold,
  n = nrow(predictions),
  positive = sum(truth == 1),
  negative = sum(truth == 0),
  tp = tp, fp = fp, tn = tn, fn = fn,
  precision = precision,
  recall = recall,
  f1 = f1
)
write_csv(metrics, file.path(tables, "r_model_metrics.csv"))

thresholds <- sort(unique(predictions$y_score), decreasing = TRUE)
pr <- lapply(thresholds, function(cutoff) {
  pred <- as.integer(predictions$y_score >= cutoff)
  tp_i <- sum(pred == 1 & truth == 1)
  fp_i <- sum(pred == 1 & truth == 0)
  fn_i <- sum(pred == 0 & truth == 1)
  tibble(
    threshold = cutoff,
    precision = safe_divide(tp_i, tp_i + fp_i),
    recall = safe_divide(tp_i, tp_i + fn_i)
  )
}) |>
  bind_rows() |>
  arrange(recall, precision)

write_csv(pr, file.path(tables, "r_precision_recall_curve.csv"))

p_pr <- ggplot(pr, aes(x = recall, y = precision)) +
  geom_path(colour = "#08519c", linewidth = 1) +
  geom_point(colour = "#08519c", size = 1.2) +
  coord_cartesian(xlim = c(0, 1), ylim = c(0, 1)) +
  labs(
    title = "Precision-recall curve on the held-out period",
    subtitle = sprintf("0.5-threshold F1 = %s", ifelse(is.na(f1), "undefined", sprintf("%.3f", f1))),
    x = "Recall", y = "Precision",
    caption = "Generated only from real held-out predictions; no synthetic points."
  )

ggsave(file.path(figures, "fig_precision_recall.png"), p_pr,
       width = 7, height = 5.5, dpi = 150)

notes <- c(
  "# R model-evaluation results",
  "",
  sprintf("- Held-out observations: %d", nrow(predictions)),
  sprintf("- Events: %d; non-events: %d", sum(truth == 1), sum(truth == 0)),
  sprintf("- Confusion matrix at 0.5: TP %d, FP %d, TN %d, FN %d", tp, fp, tn, fn),
  sprintf("- Precision: %s", ifelse(is.na(precision), "undefined", sprintf("%.3f", precision))),
  sprintf("- Recall: %s", ifelse(is.na(recall), "undefined", sprintf("%.3f", recall))),
  sprintf("- F1: %s", ifelse(is.na(f1), "undefined", sprintf("%.3f", f1))),
  "",
  "These metrics are valid only for the documented held-out split. Do not",
  "interpret them as operational warning performance without a prospective test."
)
writeLines(notes, file.path(tables, "r_model_evaluation_notes.md"), useBytes = TRUE)

message("R model evaluation complete")
